// A reworked cover dropped in src/lab/itch-covers/new/<id>.png (630x500)
// shows up beside the current one; new/<id>-315.png is its natively drawn
// 315x250, which the itch grids use; new/<id>-alt.png is a second option.
for (const g of games) {
  g.files.new = join(LAB, `new/${g.id}.png`);
  g.files.new315 = join(LAB, `new/${g.id}-315.png`);
  g.files.alt = join(LAB, `new/${g.id}-alt.png`);
}

export const fileId = (g: Game, kind: Kind) => `${g.id}--${kind}`;
